"""Real-data backtest seeding (FR-BT-1/2): build a :class:`BacktestRequest` from REAL bars.

A backtest needs two inputs the rest of the harness does not synthesize: a market-context
:class:`~trading.domain.prices.PriceSeries` and a stream of recorded
:class:`~trading.domain.signals.Signal`s to replay. This helper assembles both:

1. **Prices** come from whatever :class:`HistoricalPricesPort` the caller injects — the real
   Alpaca daily-bars adapter when historical data is enabled, or the offline synthetic path
   otherwise. The application layer never imports either concrete adapter; the composition
   root (a script or ``main``) picks one and passes it in, keeping this module pure of
   infrastructure (it depends only on the port and domain types).

2. **Signals** are generated by a *deterministic, seeded* scenario so a given
   ``(tickers, date range, seed)`` always backtests to the identical result (reproducibility
   is the whole point of a strategy-iteration loop). The scenario is described on
   :func:`seeded_signals`.

The result is a ready-to-run :class:`BacktestRequest`; the caller hands it to
``Backtest.run`` unchanged, so the seeded path exercises the exact strategy/risk/execution
code used live (FR-BT-1).
"""

import random
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import datetime, timedelta
from decimal import Decimal

from trading.application.backtest import BacktestRequest
from trading.application.ports.historical import HistoricalPricesPort
from trading.application.risk import RiskLimits
from trading.domain.prices import PriceSeries
from trading.domain.provenance import Provenance
from trading.domain.signals import Signal, SignalSource
from trading.strategies.base import Strategy

# Default seeded-scenario cadence: emit a corroborated signal burst every N days. A burst
# pairs two independent source types per ticker so conviction can clear the trade threshold
# (a single source typically only reaches "watch").
_DEFAULT_BURST_INTERVAL_DAYS = 7
# Source types rotated through to corroborate a burst (>=2 distinct types lifts conviction).
_BURST_SOURCES: tuple[SignalSource, ...] = (
    SignalSource.STATEMENT,
    SignalSource.CONTRACT,
    SignalSource.DISCLOSED_TRADE,
)


@dataclass(frozen=True, slots=True)
class SeededScenario:
    """Knobs for the deterministic signal scenario (FR-BT-1).

    Attributes:
        seed: RNG seed. The same seed + inputs reproduce the identical signal stream.
        burst_interval_days: Days between corroborated signal bursts.
        sources_per_burst: Distinct source types corroborating each burst (>=1). More
            corroboration -> higher conviction; >=2 is needed to clear a default trade
            threshold.
        min_sentiment: Lower bound of the per-signal bullish sentiment draw.
        max_sentiment: Upper bound of the per-signal bullish sentiment draw.
        politician_weight: Politician influence weight stamped on every seeded signal.
    """

    seed: int = 1729
    burst_interval_days: int = _DEFAULT_BURST_INTERVAL_DAYS
    sources_per_burst: int = 2
    min_sentiment: float = 0.7
    max_sentiment: float = 1.0
    politician_weight: float = 1.5

    def __post_init__(self) -> None:
        if self.burst_interval_days < 1:
            raise ValueError("burst_interval_days must be >= 1")
        if not 1 <= self.sources_per_burst <= len(_BURST_SOURCES):
            raise ValueError(f"sources_per_burst must be in 1..{len(_BURST_SOURCES)}")
        if not -1.0 <= self.min_sentiment <= self.max_sentiment <= 1.0:
            raise ValueError("require -1 <= min_sentiment <= max_sentiment <= 1")


def seeded_signals(
    tickers: Sequence[str],
    start: datetime,
    end: datetime,
    *,
    scenario: SeededScenario | None = None,
) -> tuple[Signal, ...]:
    """Generate a deterministic, seeded stream of bullish corroborated signals (FR-BT-1).

    Scenario: walking from ``start`` to ``end`` in ``burst_interval_days`` steps, each ticker
    emits a *burst* of ``sources_per_burst`` signals — one per distinct source type — all
    timestamped at that step. Pairing independent sources is what lets conviction clear the
    trade threshold, so the seeded run actually trades rather than only watching. Sentiment is
    drawn from ``[min_sentiment, max_sentiment]`` by a seeded RNG, so the stream is identical
    for the same ``(tickers, start, end, scenario.seed)`` — reproducible by construction.

    Signal ids are deterministic (``seed-ticker-step-source``), not random UUIDs, so two runs
    produce byte-identical signals.
    """
    cfg = scenario or SeededScenario()
    # Scenario reproducibility, not cryptography: a seeded Mersenne-Twister is intentional.
    rng = random.Random(cfg.seed)
    sources = _BURST_SOURCES[: cfg.sources_per_burst]
    ordered_tickers = sorted({t.strip().upper() for t in tickers if t.strip()})

    signals: list[Signal] = []
    when = start
    step = 0
    while when <= end:
        for ticker in ordered_tickers:
            for source in sources:
                sentiment = rng.uniform(cfg.min_sentiment, cfg.max_sentiment)
                signals.append(
                    Signal(
                        id=f"seed-{ticker}-{step}-{source.value}",
                        created_at=when,
                        source_type=source,
                        ticker=ticker,
                        politician_id="seed-politician",
                        sentiment=sentiment,
                        politician_weight=cfg.politician_weight,
                        source_reliability=1.0,
                        raw_payload={"seeded": True, "step": step},
                        # Explicitly SYNTHETIC: seeded signals are a plumbing fixture, never real
                        # data. The trade-time guard would reject them on any real broker.
                        provenance=Provenance.SYNTHETIC,
                    )
                )
        step += 1
        when += timedelta(days=cfg.burst_interval_days)
    return tuple(signals)


@dataclass(frozen=True, slots=True)
class SeededBacktest:
    """A seeded backtest plan: the assembled request plus the metadata used to build it."""

    request: BacktestRequest
    symbols: tuple[str, ...]
    start: datetime
    end: datetime
    signal_count: int


async def build_seeded_request(
    *,
    historical_prices: HistoricalPricesPort,
    strategy: Strategy,
    tickers: Sequence[str],
    start: datetime,
    end: datetime,
    risk_limits: RiskLimits,
    starting_cash: Decimal,
    window_days: int,
    scenario: SeededScenario | None = None,
) -> SeededBacktest:
    """Assemble a :class:`BacktestRequest` from REAL bars + seeded signals (FR-BT-1/2).

    Pulls the per-symbol :class:`PriceSeries` over ``[start, end]`` from the injected
    ``historical_prices`` port (real Alpaca bars or the synthetic fallback — the caller
    decides which), generates the deterministic seeded signal stream, and packages both into a
    request ready for ``Backtest.run``. The returned :class:`SeededBacktest` also carries the
    resolved symbols and signal count for reporting.
    """
    symbols = tuple(sorted({t.strip().upper() for t in tickers if t.strip()}))
    prices: PriceSeries = await historical_prices.price_series(symbols, start, end)
    signals = seeded_signals(symbols, start, end, scenario=scenario)
    request = BacktestRequest(
        strategy=strategy,
        signals=signals,
        risk_limits=risk_limits,
        prices=prices,
        starting_cash=starting_cash,
        window_days=window_days,
    )
    return SeededBacktest(
        request=request,
        symbols=symbols,
        start=start,
        end=end,
        signal_count=len(signals),
    )
